const std = @import("std");
const manifest = @import("manifest.zig");
const font_digest = @import("digest.zig");
const knots_text = @import("text");

const Io = std.Io;

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    var args = try init.minimal.args.iterateAllocator(arena);
    _ = args.next();
    const command = args.next() orelse return error.MissingCommand;
    const root_path = args.next() orelse return error.MissingRoot;
    var root = try Io.Dir.cwd().openDir(init.io, root_path, .{});
    defer root.close(init.io);

    if (std.mem.eql(u8, command, "fetch")) return fetch(init.io, init.gpa, arena, root);
    if (std.mem.eql(u8, command, "digests")) return generateDigests(init.io, init.gpa, arena, root);
    return error.UnknownCommand;
}

fn generateDigests(io: Io, gpa: std.mem.Allocator, arena: std.mem.Allocator, root: Io.Dir) !void {
    const fonts_text = try root.readFileAlloc(io, manifest.fonts_path, arena, .unlimited);
    const fonts = try manifest.parseFonts(arena, fonts_text);
    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(arena, "# Generated by `zig build digests`: name | glyphs | cmap | advances | outlines\n");
    for (fonts) |font| {
        if (font.isDirectory()) continue;
        const data = try root.readFileAlloc(io, try font.fontPath(arena), arena, .unlimited);
        var program = try knots_text.FontProgram.init(gpa, data, 0);
        defer program.deinit();
        try font_digest.appendLine(arena, &out, font.name, try font_digest.compute(gpa, &program));
    }
    try root.writeFile(io, .{ .sub_path = font_digest.path, .data = out.items });
}

fn fetch(io: Io, gpa: std.mem.Allocator, arena: std.mem.Allocator, root: Io.Dir) !void {
    const fonts_text = try root.readFileAlloc(io, manifest.fonts_path, arena, .unlimited);
    const entries = try manifest.parseFonts(arena, fonts_text);
    try root.createDirPath(io, manifest.cache_dir ++ "/downloads");
    try root.createDirPath(io, manifest.cache_dir ++ "/fonts");

    var client: std.http.Client = .{ .allocator = gpa, .io = io };
    defer client.deinit();

    for (entries) |entry| {
        if (entry.localPath()) |path| {
            try verifyFile(io, arena, root, path, entry.sha256);
            continue;
        }
        const download = try std.fmt.allocPrint(arena, "{s}/downloads/{s}", .{ manifest.cache_dir, entry.sha256 });
        if (!try hashMatches(io, arena, root, download, entry.sha256)) {
            std.debug.print("downloading {s}\n", .{entry.downloadUrl()});
            try downloadTo(io, &client, root, entry.downloadUrl(), download);
            try verifyFile(io, arena, root, download, entry.sha256);
        }
        try install(io, arena, root, entry, download);
    }
}

fn downloadTo(io: Io, client: *std.http.Client, root: Io.Dir, url: []const u8, path: []const u8) !void {
    const partial = try std.fmt.allocPrint(client.allocator, "{s}.partial", .{path});
    defer client.allocator.free(partial);
    {
        var file = try root.createFile(io, partial, .{});
        defer file.close(io);
        var buffer: [64 * 1024]u8 = undefined;
        var writer = file.writer(io, &buffer);
        const result = try client.fetch(.{ .location = .{ .url = url }, .response_writer = &writer.interface });
        try writer.interface.flush();
        if (result.status != .ok) {
            std.debug.print("{s}: HTTP {d}\n", .{ url, @backingInt(result.status) });
            return error.DownloadFailed;
        }
    }
    try root.rename(partial, root, path, io);
}

fn hashMatches(io: Io, arena: std.mem.Allocator, root: Io.Dir, path: []const u8, expected: []const u8) !bool {
    const bytes = root.readFileAlloc(io, path, arena, .unlimited) catch |err| switch (err) {
        error.FileNotFound => return false,
        else => return err,
    };
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    const hex = std.fmt.bytesToHex(digest, .lower);
    return std.mem.eql(u8, &hex, expected);
}

fn verifyFile(io: Io, arena: std.mem.Allocator, root: Io.Dir, path: []const u8, expected: []const u8) !void {
    if (try hashMatches(io, arena, root, path, expected)) return;
    std.debug.print("{s}: sha256 mismatch, expected {s}\n", .{ path, expected });
    return error.HashMismatch;
}

fn install(io: Io, arena: std.mem.Allocator, root: Io.Dir, entry: manifest.FontEntry, download: []const u8) !void {
    const archive_path = entry.archivePath() orelse {
        const target = try entry.fontPath(arena);
        try root.copyFile(download, root, target, io, .{});
        return;
    };
    if (std.mem.endsWith(u8, entry.downloadUrl(), ".zip") and entry.isDirectory()) {
        const target = try std.fmt.allocPrint(arena, "{s}/{s}", .{ manifest.cache_dir, entry.name });
        return extractZipPrefix(io, arena, root, download, archivePrefix(archive_path), target);
    }
    if (std.mem.endsWith(u8, entry.downloadUrl(), ".zip")) {
        const target = try entry.fontPath(arena);
        return extractZipEntry(io, root, download, archive_path, target);
    }
    return error.UnknownArchive;
}

fn extractZipEntry(io: Io, root: Io.Dir, archive: []const u8, wanted: []const u8, target: []const u8) !void {
    var file = try root.openFile(io, archive, .{});
    defer file.close(io);
    var read_buffer: [64 * 1024]u8 = undefined;
    var reader = file.reader(io, &read_buffer);
    var iterator = try std.zip.Iterator.init(&reader);
    var name_buffer: [std.fs.max_path_bytes]u8 = undefined;
    while (try iterator.next()) |entry| {
        const name = try entry.getFilename(&reader, &name_buffer, .{});
        if (!std.mem.eql(u8, name, wanted)) continue;
        var out = try root.createFile(io, target, .{});
        defer out.close(io);
        var write_buffer: [64 * 1024]u8 = undefined;
        var writer = out.writer(io, &write_buffer);
        try entry.extractTo(&reader, &writer.interface);
        try writer.interface.flush();
        return;
    }
    std.debug.print("{s}: no entry {s}\n", .{ archive, wanted });
    return error.MissingArchiveEntry;
}

fn archivePrefix(path: []const u8) []const u8 {
    if (std.mem.eql(u8, path, "/")) return "";
    return path;
}

fn extractZipPrefix(io: Io, arena: std.mem.Allocator, root: Io.Dir, archive: []const u8, prefix: []const u8, target: []const u8) !void {
    var file = try root.openFile(io, archive, .{});
    defer file.close(io);
    var read_buffer: [64 * 1024]u8 = undefined;
    var reader = file.reader(io, &read_buffer);
    var iterator = try std.zip.Iterator.init(&reader);
    var name_buffer: [std.fs.max_path_bytes]u8 = undefined;
    var count: usize = 0;
    while (try iterator.next()) |entry| {
        const name = try entry.getFilename(&reader, &name_buffer, .{});
        if (std.mem.endsWith(u8, name, "/") or !std.mem.startsWith(u8, name, prefix)) continue;
        const path = try std.fmt.allocPrint(arena, "{s}/{s}", .{ target, name[prefix.len..] });
        if (std.fs.path.dirname(path)) |directory| try root.createDirPath(io, directory);
        var out = try root.createFile(io, path, .{});
        defer out.close(io);
        var write_buffer: [64 * 1024]u8 = undefined;
        var writer = out.writer(io, &write_buffer);
        try entry.extractTo(&reader, &writer.interface);
        try writer.interface.flush();
        count += 1;
    }
    if (count == 0) return error.MissingArchiveEntry;
}
