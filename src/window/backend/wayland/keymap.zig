const window = @import("window");

const Key = window.Key;

pub fn translateEvdev(code: u32) Key {
    return switch (code) {
        1 => .escape,
        2...11 => @enumFromInt(@intFromEnum(Key.@"1") + @as(i32, @intCast(code - 2))),
        12 => .minus,
        13 => .equal,
        14 => .backspace,
        15 => .tab,
        16 => .q,
        17 => .w,
        18 => .e,
        19 => .r,
        20 => .t,
        21 => .y,
        22 => .u,
        23 => .i,
        24 => .o,
        25 => .p,
        26 => .left_bracket,
        27 => .right_bracket,
        28 => .enter,
        29 => .left_control,
        30 => .a,
        31 => .s,
        32 => .d,
        33 => .f,
        34 => .g,
        35 => .h,
        36 => .j,
        37 => .k,
        38 => .l,
        39 => .semicolon,
        40 => .apostrophe,
        41 => .grave_accent,
        42 => .left_shift,
        43 => .backslash,
        44 => .z,
        45 => .x,
        46 => .c,
        47 => .v,
        48 => .b,
        49 => .n,
        50 => .m,
        51 => .comma,
        52 => .period,
        53 => .slash,
        54 => .right_shift,
        55 => .kp_multiply,
        56 => .left_alt,
        57 => .space,
        58 => .caps_lock,
        59...68 => @enumFromInt(@intFromEnum(Key.f1) + @as(i32, @intCast(code - 59))),
        69 => .num_lock,
        70 => .scroll_lock,
        71 => .kp_7,
        72 => .kp_8,
        73 => .kp_9,
        74 => .kp_subtract,
        75 => .kp_4,
        76 => .kp_5,
        77 => .kp_6,
        78 => .kp_add,
        79 => .kp_1,
        80 => .kp_2,
        81 => .kp_3,
        82 => .kp_0,
        83 => .kp_decimal,
        87 => .f11,
        88 => .f12,
        96 => .kp_enter,
        97 => .right_control,
        98 => .kp_divide,
        99 => .print_screen,
        100 => .right_alt,
        102 => .home,
        103 => .up,
        104 => .page_up,
        105 => .left,
        106 => .right,
        107 => .end,
        108 => .down,
        109 => .page_down,
        110 => .insert,
        111 => .delete,
        119 => .pause,
        125 => .left_super,
        126 => .right_super,
        127 => .menu,
        183...194 => @enumFromInt(@intFromEnum(Key.f13) + @as(i32, @intCast(code - 183))),
        else => @enumFromInt(0),
    };
}
